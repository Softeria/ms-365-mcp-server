#!/usr/bin/env npx tsx
/**
 * Writes PRESETS.md from the live preset → tool mapping in tool-categories.ts.
 * Invoked by `npm run generate`.
 */
import { writeFileSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import prettier from 'prettier';
import { resolveAuthScopes } from '../src/auth.js';
import { buildToolsRegistry, shouldExposeUtilityTool, UTILITY_TOOLS } from '../src/graph-tools.js';
import { getCombinedPresetPattern, listPresets } from '../src/tool-categories.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const outFile = path.join(rootDir, 'PRESETS.md');

type Mode = 'full' | 'read-only';

function modeLabel(mode: Mode): string {
  return mode === 'full' ? 'full' : 'read only';
}

function sectionAnchor(preset: string, mode: Mode): string {
  return `${preset}-${mode}`;
}

/**
 * Tools the server would expose for `--preset X` [--read-only], using the same
 * Graph registry filters as runtime. Always pass orgMode so work-scoped tools that
 * belong to a personal preset (e.g. SharePoint OneNote under `onenote`) are listed.
 * httpMode=false keeps stdioOnly utilities in the catalog. Strip `enabled` so
 * process opt-in (e.g. MS365_MCP_UPLOAD_DIRS) does not shrink the documented set.
 */
function toolsForMode(preset: string, mode: Mode): string[] {
  const readOnly = mode === 'read-only';
  const enabledToolsRegex = new RegExp(getCombinedPresetPattern([preset]));
  const graphTools = [...buildToolsRegistry(readOnly, true, enabledToolsRegex).keys()];
  const utilityTools = UTILITY_TOOLS.filter((u) =>
    shouldExposeUtilityTool({ ...u, enabled: undefined }, readOnly, false, enabledToolsRegex)
  ).map((u) => u.name);
  return [...new Set([...graphTools, ...utilityTools])].sort();
}

function scopesForMode(preset: string, mode: Mode): string[] {
  return resolveAuthScopes({
    enabledTools: getCombinedPresetPattern([preset]),
    readOnly: mode === 'read-only',
    orgMode: true,
  });
}

function pushBulletList(lines: string[], heading: string, items: string[]): void {
  lines.push(`${heading} (${items.length}):`);
  lines.push('');
  for (const item of items) {
    lines.push(`- \`${item}\``);
  }
  lines.push('');
}

export async function renderPresetsMarkdown(): Promise<string> {
  const catalog = listPresets().map((preset) => {
    const fullTools = toolsForMode(preset.name, 'full');
    const readOnlyTools = toolsForMode(preset.name, 'read-only');
    return {
      ...preset,
      variants: [
        {
          mode: 'full' as const,
          tools: fullTools,
          scopes: scopesForMode(preset.name, 'full'),
        },
        {
          mode: 'read-only' as const,
          tools: readOnlyTools,
          scopes: scopesForMode(preset.name, 'read-only'),
        },
      ],
    };
  });

  const lines: string[] = [
    '# Tool Presets',
    '',
    '> Generated by `bin/generate-presets-md.ts`. Do not edit by hand; regenerated on `npm run generate`.',
    '',
    '',
    '## Summary',
    '',
    '| Preset | Mode | Tools | Scopes | Org mode | Description |',
    '| ------ | ---- | ----: | -----: | -------- | ----------- |',
  ];

  for (const entry of catalog) {
    const org = entry.requiresOrgMode ? 'required' : '-';
    const desc = entry.description.replace(/\|/g, '\\|');
    const modeCell = entry.variants
      .map((v) => `[${modeLabel(v.mode)}](#${sectionAnchor(entry.name, v.mode)})`)
      .join('<br>');
    const toolsCell = entry.variants.map((v) => String(v.tools.length)).join('<br>');
    const scopesCell = entry.variants.map((v) => String(v.scopes.length)).join('<br>');
    // Same org-mode flag for both variants; still stacked so the row lines up with Mode/Tools.
    const orgCell = entry.variants.map(() => org).join('<br>');
    lines.push(
      `| \`${entry.name}\` | ${modeCell} | ${toolsCell} | ${scopesCell} | ${orgCell} | ${desc} |`
    );
  }

  lines.push('');

  for (const entry of catalog) {
    for (const variant of entry.variants) {
      const label = modeLabel(variant.mode);
      lines.push(`## \`${entry.name}\` ${label}`);
      lines.push('');
      lines.push(entry.description);
      if (entry.requiresOrgMode) {
        lines.push('');
        lines.push('Requires `--org-mode`.');
      }
      lines.push('');
      pushBulletList(lines, 'Tools', variant.tools);
      pushBulletList(lines, 'Scopes', variant.scopes);
    }
  }

  // Format here so PRESETS.md matches `prettier --check` and the staleness test.
  return prettier.format(lines.join('\n'), { filepath: outFile });
}

async function main(): Promise<void> {
  const presets = listPresets();
  writeFileSync(outFile, await renderPresetsMarkdown(), 'utf8');
  console.log(`Wrote ${path.relative(rootDir, outFile)} (${presets.length} presets)`);
}

const isDirectRun =
  process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isDirectRun) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}
